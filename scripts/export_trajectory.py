"""Export the Phosphorus 1 heliocentric geometry for the web viewer.

Writes assets/trajectory.js. Positions are ecliptic x/y in AU, sampled
every 2 days. The transfer arcs are the actual Lambert solutions used
elsewhere in the plan -- propagated with a universal-variable f/g
two-body propagator, not drawn by hand.
"""
import json
import math
import os
from datetime import date, timedelta

from porkchop import (AU, DAY, MU_SUN, jd_from_date, lambert, norm, dot,
                      planet_state, stumpff_C, stumpff_S)

DEP = date(2042, 7, 27)
VARR = date(2042, 11, 28)
VDEP = date(2042, 12, 28)
EARR = date(2043, 10, 29)


def propagate(r0, v0, dt):
    """Universal-variable Kepler propagation. dt in seconds."""
    r0n, v0n = norm(r0), norm(v0)
    alpha = 2.0 / r0n - v0n ** 2 / MU_SUN
    sq = math.sqrt(MU_SUN)
    x = sq * abs(alpha) * dt
    rdotv = dot(r0, v0)
    for _ in range(120):
        z = alpha * x * x
        C, S = stumpff_C(z), stumpff_S(z)
        F = (rdotv / sq) * x * x * C + (1 - alpha * r0n) * x ** 3 * S + r0n * x - sq * dt
        dF = (rdotv / sq) * x * (1 - z * S) + (1 - alpha * r0n) * x * x * C + r0n
        dx = F / dF
        x -= dx
        if abs(dx) < 1e-8:
            break
    z = alpha * x * x
    C, S = stumpff_C(z), stumpff_S(z)
    f = 1 - x * x / r0n * C
    g = dt - x ** 3 / sq * S
    return [f * r0[k] + g * v0[k] for k in range(3)]


def arc(d0, d1, p_from, p_to, step=2):
    jd0, jd1 = jd_from_date(d0), jd_from_date(d1)
    r1, _ = planet_state(p_from, jd0)
    r2, _ = planet_state(p_to, jd1)
    v0, _ = lambert(r1, r2, (jd1 - jd0) * DAY)
    pts = []
    n = int((d1 - d0).days)
    for k in range(0, n + 1, step):
        r = propagate(r1, v0, k * DAY) if k else r1
        pts.append([round(r[0] / AU, 5), round(r[1] / AU, 5)])
    rr, _ = planet_state(p_to, jd1)
    pts.append([round(rr[0] / AU, 5), round(rr[1] / AU, 5)])
    return pts


def track(body, d0, d1, step=2):
    pts = []
    n = int((d1 - d0).days)
    for k in range(0, n + 1, step):
        r, _ = planet_state(body, jd_from_date(d0 + timedelta(days=k)))
        pts.append([round(r[0] / AU, 5), round(r[1] / AU, 5)])
    return pts


def orbit(body, d0, step=6):
    period = {'earth': 365.256, 'venus': 224.701}[body]
    pts = []
    k = 0.0
    while k <= period + step:
        r, _ = planet_state(body, jd_from_date(d0) + k)
        pts.append([round(r[0] / AU, 5), round(r[1] / AU, 5)])
        k += step
    return pts


data = {
    'dates': {
        'depart': DEP.isoformat(), 'venusArrive': VARR.isoformat(),
        'venusDepart': VDEP.isoformat(), 'earthArrive': EARR.isoformat()
    },
    'orbitEarth': orbit('earth', DEP),
    'orbitVenus': orbit('venus', DEP),
    'outbound': arc(DEP, VARR, 'earth', 'venus'),
    'inbound': arc(VDEP, EARR, 'venus', 'earth'),
    'earthTrack': track('earth', DEP, EARR),
    'venusTrack': track('venus', DEP, EARR),
    'marks': {}
}
for key, d in (('depart', DEP), ('venusArrive', VARR), ('venusDepart', VDEP), ('earthArrive', EARR)):
    e, _ = planet_state('earth', jd_from_date(d))
    v, _ = planet_state('venus', jd_from_date(d))
    data['marks'][key] = {
        'earth': [round(e[0] / AU, 5), round(e[1] / AU, 5)],
        'venus': [round(v[0] / AU, 5), round(v[1] / AU, 5)],
        'day': (d - DEP).days
    }
data['totalDays'] = (EARR - DEP).days

out = os.path.join(os.path.dirname(__file__), '..', 'assets', 'trajectory.js')
with open(out, 'w') as f:
    f.write('/* Generated by scripts/export_trajectory.py — do not edit by hand.\n')
    f.write('   Heliocentric ecliptic x/y in AU, 2-day sampling.\n')
    f.write('   Transfer arcs are the Lambert solutions from the mission plan. */\n\n')
    f.write('var PHOS = (window.PHOS = window.PHOS || {});\n')
    f.write('PHOS.TRAJ = ')
    f.write(json.dumps(data, separators=(',', ':')))
    f.write(';\n')
print('wrote', os.path.normpath(out))
print('outbound pts', len(data['outbound']), 'inbound pts', len(data['inbound']))
